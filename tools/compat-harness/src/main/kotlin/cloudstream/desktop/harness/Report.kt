package cloudstream.desktop.harness

object Report {
    /** Extensions listed first and in full (`--priority A,B`). */
    @Volatile var priorityNames: List<String> = emptyList()

    fun isPriority(name: String, internal: String) = priorityNames.any { it.equals(name, true) || it.equals(internal, true) }
    fun isAnime(tvTypes: List<String>) = tvTypes.any { it.equals("Anime", true) || it.equals("OVA", true) || it.equals("AnimeMovie", true) }

    /** Aggregate a stage over a plugin's providers: "pass", "FAIL", "fail 1/3", "skip", or "-" when it never ran. */
    fun cell(p: PluginResult, stage: String): String {
        when (stage) {
            "convert" -> return p.convert?.status?.let { if (it == Status.PASS) "pass" else "FAIL" } ?: "-"
            "load-plugin" -> return p.load?.status?.let { if (it == Status.PASS) "pass" else "FAIL" } ?: "-"
        }
        val rows = p.providers.mapNotNull { pr -> pr.stages.firstOrNull { it.stage == stage } }
        if (rows.isEmpty()) return "-"
        val fails = rows.count { it.status == Status.FAIL }
        val passes = rows.count { it.status == Status.PASS }
        return when {
            fails == 0 && passes == 0 -> "skip"
            fails == 0 -> "pass"
            rows.size == 1 -> "FAIL"
            else -> "FAIL $fails/${rows.size}"
        }
    }

    private fun esc(s: String?) = (s ?: "").replace("|", "\\|").replace("\n", " ").replace("`", "'")

    fun errorSummary(p: PluginResult): String {
        val st = p.firstFailure()
        val e = st?.error ?: p.processFailure ?: return ""
        val sym = e.symbol?.let { " [${it.take(110)}]" } ?: ""
        val where = st?.let { "(${it.stage}) " } ?: ""
        return esc("$where${e.cls.substringAfterLast('.')}: ${e.message?.take(100) ?: ""}$sym ${e.frame ?: e.rootFrame ?: ""}".trim())
    }

    data class Counts(var pass: Int = 0, var fail: Int = 0, var skip: Int = 0) {
        val rate get() = if (pass + fail == 0) "n/a" else "%.0f%% (%d/%d)".format(100.0 * pass / (pass + fail), pass, pass + fail)
    }

    fun stageCounts(plugins: List<PluginResult>): Map<String, Counts> {
        val m = linkedMapOf("convert" to Counts(), "load-plugin" to Counts()) + STAGES.associateWith { Counts() }
        for (p in plugins) {
            p.convert?.let { tally(m["convert"]!!, it.status) }
            p.load?.let { tally(m["load-plugin"]!!, it.status) }
            p.providers.forEach { pr -> pr.stages.forEach { s -> m[s.stage]?.let { tally(it, s.status) } } }
        }
        return m
    }

    private fun tally(c: Counts, s: Status) = when (s) { Status.PASS -> c.pass++; Status.FAIL -> c.fail++; Status.SKIP -> c.skip++ }

    fun bucketOrder(id: String?) = if (id == null) Int.MAX_VALUE else Bucket.entries.indexOfFirst { it.id == id }.let { if (it < 0) 99 else it }

    fun markdown(run: Run, diff: List<String>, args: String): String {
        val sb = StringBuilder()
        val ps = run.plugins
        val live = ps.filter { it.knownBroken == null }
        sb.appendLine("# Compatibility matrix").appendLine()
        sb.appendLine("Generated by `tools/compat-harness` at ${run.startedAt}. Each plugin ran in its own child JVM; live network.")
        sb.appendLine("Command: `$args`").appendLine()
        sb.appendLine("Repos: " + run.repos.joinToString(", ") { "`$it`" }).appendLine()

        sb.appendLine("## Summary").appendLine()
        val fullPass = ps.count { it.passed() }
        sb.appendLine("- Plugins: **${ps.size}**; fully passing (converted + loaded + no failing stage): **$fullPass**; known-broken upstream: ${ps.count { it.knownBroken != null }}.")
        sb.appendLine()
        sb.appendLine("Stage pass rate (provider-level rows; SKIP not counted):").appendLine()
        sb.appendLine("| Stage | All | " + run.repos.indices.joinToString(" | ") { repoLabel(run, it) } + " |")
        sb.appendLine("|---|---|" + run.repos.joinToString("") { "---|" })
        val all = stageCounts(ps)
        val perRepo = run.repos.map { r -> stageCounts(ps.filter { it.repo == r }) }
        for (st in all.keys) sb.appendLine("| $st | ${all[st]!!.rate} | " + perRepo.joinToString(" | ") { it[st]!!.rate } + " |")
        sb.appendLine()
        sb.appendLine("Per repo: " + run.repos.joinToString("; ") { r ->
            val l = ps.filter { it.repo == r }
            "${repoLabel(run, run.repos.indexOf(r))}: ${l.size} plugins, ${l.count { it.convert?.status == Status.PASS }} converted, ${l.count { it.load?.status == Status.PASS }} loaded, ${l.count { it.passed() }} fully passing, ${l.count { p -> p.providers.any { pr -> pr.stages.any { it.stage == "search" && it.status == Status.PASS } } }} with a working search"
        }).appendLine()

        // buckets
        sb.appendLine("## Failure buckets (plugins, by earliest failing stage)").appendLine()
        sb.appendLine("| Bucket | Plugins | Not known-broken | Meaning |").appendLine("|---|---|---|---|")
        val byBucket = ps.filter { it.bucket() != null }.groupBy { it.bucket()!! }
        for ((b, l) in byBucket.entries.sortedBy { bucketOrder(it.key) })
            sb.appendLine("| $b | ${l.size} | ${l.count { it.knownBroken == null }} | ${Bucket.of(b)?.blurb ?: ""} |")
        sb.appendLine()
        val syms = ps.flatMap { p -> p.allStages().filter { it.status == Status.FAIL }.mapNotNull { it.error?.symbol }.distinct().map { it to p.name } }
        if (syms.isNotEmpty()) {
            sb.appendLine("### Top missing symbols").appendLine()
            sb.appendLine("| Symbol | Plugins | Which |").appendLine("|---|---|---|")
            syms.groupBy({ it.first }, { it.second }).entries.sortedByDescending { it.value.size }.take(25).forEach {
                sb.appendLine("| `${esc(it.key)}` | ${it.value.size} | ${esc(it.value.distinct().take(6).joinToString(", "))} |")
            }
            sb.appendLine()
        }
        val frames = ps.mapNotNull { p -> p.firstFailure()?.takeIf { it.bucket == Bucket.CORE.id }?.error?.let { (it.cls + " @ " + (it.frame ?: it.rootFrame ?: "?")) to p.name } }
        if (frames.isNotEmpty()) {
            sb.appendLine("### Top core-behavior sites").appendLine()
            sb.appendLine("| Exception @ first non-JDK frame | Plugins |").appendLine("|---|---|")
            frames.groupBy({ it.first }, { it.second }).entries.sortedByDescending { it.value.size }.take(15).forEach {
                sb.appendLine("| `${esc(it.key)}` | ${it.value.size}: ${esc(it.value.take(5).joinToString(", "))} |")
            }
            sb.appendLine()
        }

        fun table(title: String, list: List<PluginResult>) {
            if (list.isEmpty()) return
            sb.appendLine("## $title").appendLine()
            sb.appendLine("| Plugin | Repo | convert | load | getMainPage | search | load() | loadLinks | Bucket | First failure | Notes |")
            sb.appendLine("|---|---|---|---|---|---|---|---|---|---|---|")
            for (p in list.sortedWith(compareBy({ bucketOrder(it.bucket()) }, { it.name.lowercase() }))) {
                val notes = listOfNotNull(p.knownBroken?.let { "known-broken: $it" }, if (p.providers.size > 1) "${p.providers.size} providers" else null,
                    if (p.shimHits.isNotEmpty()) "${p.shimHits.size} shim stub hits" else null).joinToString("; ")
                sb.appendLine("| ${esc(p.name)} | ${repoLabel(run, run.repos.indexOf(p.repo))} | ${cell(p, "convert")} | ${cell(p, "load-plugin")} | ${cell(p, "getMainPage")} | ${cell(p, "search")} | ${cell(p, "load")} | ${cell(p, "loadLinks")} | ${p.bucket() ?: (if (p.passed()) "pass" else "-")} | ${errorSummary(p)} | ${esc(notes)} |")
            }
            sb.appendLine()
        }
        table("Priority plugins", ps.filter { it.priority })
        table("Anime providers", ps.filter { !it.priority && isAnime(it.tvTypes) })
        table("All other plugins", ps.filter { !it.priority && !isAnime(it.tvTypes) })

        sb.appendLine("## Diff against previous run").appendLine()
        if (diff.isEmpty()) sb.appendLine("No changes (or no previous run).") else diff.forEach { sb.appendLine("- $it") }
        sb.appendLine()
        sb.appendLine("## Caveats").appendLine()
        sb.appendLine("- Live network and live sites: `external` and `no-result` rows can flip between runs (geo-blocks, rate limits, site churn). Compare against `known-broken.json` and re-run before treating a row as a regression.")
        sb.appendLine("- A stage passes only when it returns data (`loadLinks`: at least one `ExtractorLink`). Inputs are chained: `load` uses the first `search` hit (falling back to `getMainPage`), `loadLinks` uses the first movie `dataUrl` / episode of that `load` result.")
        sb.appendLine("- Only the first `mainPage` entry and the query `\"the\"` are tried. The plugin bucket is that of the earliest failing stage.")
        if (live.size != ps.size) sb.appendLine("- ${ps.size - live.size} plugin(s) are listed in `known-broken.json` or flagged down (status 0) in the repo.")
        return sb.toString()
    }

    private fun repoLabel(run: Run, i: Int) = if (i < 0) "?" else run.repos[i].substringAfter("githubusercontent.com/").substringBefore("/").ifBlank { "repo$i" }

    /** Human readable differences between two runs, keyed by plugin internalName + repo. */
    fun diff(prev: Run?, cur: Run): List<String> {
        if (prev == null) return emptyList()
        val out = ArrayList<String>()
        fun key(p: PluginResult) = p.repo + "#" + p.internalName
        val pm = prev.plugins.associateBy(::key)
        val cm = cur.plugins.associateBy(::key)
        for ((k, c) in cm) {
            val p = pm[k]
            if (p == null) { out += "NEW ${c.name}: ${state(c)}"; continue }
            if (p.bucket() != c.bucket() || p.passed() != c.passed()) out += "CHANGED ${c.name}: ${state(p)} -> ${state(c)}"
            else {
                val ps = STAGES.map { cell(p, it) }; val cs = STAGES.map { cell(c, it) }
                if (ps != cs) out += "STAGES ${c.name}: " + STAGES.indices.filter { ps[it] != cs[it] }.joinToString(", ") { "${STAGES[it]} ${ps[it]} -> ${cs[it]}" }
            }
        }
        for ((k, p) in pm) if (k !in cm) out += "REMOVED ${p.name}"
        return out.sorted()
    }

    private fun state(p: PluginResult) = if (p.passed()) "pass" else (p.bucket() ?: "incomplete")
}
